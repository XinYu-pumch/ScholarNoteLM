"""Build a self-contained offline installer without changing the source edition.

Requires the matching precompiled app, managed Windows runtimes/models, signed
WebView2 standalone installer, Inno Setup 7 and the VS2022 x64 CRT redist folder.
No downloads, pip installs, user configuration or research data are read here.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import uuid
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'scripts/standalone'))
from bootstrap import safe_path, reject_links
from install_assets import manifest as asset_manifest, matches
from release_manifest import validate

FORBIDDEN = ('config/', 'data/', 'workspace/', 'cache/', 'tmp/', 'logs/',
             'models/', 'runtimes/', 'dist/', 'backups/', '.git/', 'node_modules/')
RUNTIME_NAMES = ('downloader', 'marker', 'retrieval', 'python', 'node', 'playwright')
SECRET_PATTERNS = (rb'gh[pousr]_[A-Za-z0-9]{30,}', rb'(?<![A-Za-z0-9])sk-(?:proj-)?[A-Za-z0-9_-]{30,}',
                   rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def git(*args):
    return subprocess.check_output(['git', '-c', 'safe.directory='+ROOT.as_posix(), *args], cwd=ROOT)


def source_files():
    names = git('ls-files', '--cached', '--others', '--exclude-standard', '-z').decode('utf-8').split('\0')
    result = []
    for name in sorted(set(names)):
        if not name:
            continue
        if name.startswith(FORBIDDEN) or name in ('ScholarNoteLM.exe', 'ScholarNoteLM-Setup.exe', 'source-manifest.json'):
            raise ValueError('Private/generated path in source list: '+name)
        path = safe_path(ROOT, name)
        if not path.is_file():
            raise ValueError('Missing source file: '+name)
        data = path.read_bytes()
        if any(re.search(pattern, data) for pattern in SECRET_PATTERNS):
            raise ValueError('Credential pattern in public source: '+name)
        result.append(name)
    return result


def copy_file(source, destination):
    reject_links(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)  # New files inherit the staging/install ACL.


def runtime_files(root, component):
    tree = root/'runtimes'/component
    if not tree.is_dir():
        raise ValueError('Missing runtime: '+component)
    for directory, folders, files in os.walk(tree, followlinks=False):
        directory = Path(directory)
        reject_links(directory)
        folders[:] = [n for n in folders if n not in ('__pycache__', '.git', '.links')]
        for name in files:
            relative = (directory/name).relative_to(tree)
            if name.endswith(('.pyc', '.pyo')) or name in ('pyvenv.cfg', 'uv-cache.json', 'uv_cache.json', 'cuda-install.json', 'torch.lock'):
                continue
            # Console entry points generated by pip/uv may contain developer paths.
            # Application workers always execute the venv Python directly.
            if (component in ('downloader', 'marker', 'retrieval') or component.startswith('marker-cu')) and relative.parts[0]=='Scripts':
                if name not in ('python.exe', 'pythonw.exe'):
                    continue
            yield directory/name


def cuda_payload(root):
    """Select only the owned, lock-matched overlay; never copy a machine-wide CUDA."""
    state = json.loads((root/'runtimes/cuda-state.json').read_text(encoding='utf-8'))
    plan = json.loads((root/'scripts/install/cuda-windows-x64.json').read_text(encoding='utf-8'))
    profile = state.get('profile')
    if not state.get('ready') or profile not in plan['profiles']:
        raise ValueError('Install a managed CUDA runtime before using --include-cuda.')
    spec = importlib.util.spec_from_file_location('standalone_windows_setup',root/'scripts/setup-runtime-windows.py')
    setup = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(setup)
    fingerprint = hashlib.sha256((setup.fingerprint(root)+json.dumps(plan['profiles'][profile],sort_keys=True)).encode()).hexdigest()
    directory = 'marker-'+profile+'-'+fingerprint[:12]
    if state.get('directory')!=directory or state.get('fingerprint')!=fingerprint:
        raise ValueError('CUDA runtime does not match the current dependency locks.')
    runtime = safe_path(root,'runtimes/'+directory)
    pth = runtime/'Lib/site-packages/scholarnotelm-base.pth'
    if pth.read_text(encoding='utf-8').strip()!='../../../marker/Lib/site-packages':
        raise ValueError('CUDA overlay must use the relative bundled CPU dependencies.')
    expected = plan['torch']+'+'+profile
    subprocess.run([str(runtime/'Scripts/python.exe'),'-I','-B','-c',
                    'import torch,transformers,surya;assert torch.__version__=='+repr(expected)],
                   cwd=root,check=True,timeout=120)
    return {'schemaVersion':1,'ready':True,'directory':directory,'profile':profile,
            'fingerprint':fingerprint,'torch':expected,
            'minimumWindowsDriver':plan['profiles'][profile]['minimumWindowsDriver']}


def verify_microsoft_signature(path):
    env = {k:v for k,v in os.environ.items() if k.upper()!='PSMODULEPATH'}
    shell = Path(os.environ['SystemRoot'])/'System32/WindowsPowerShell/v1.0/powershell.exe'
    env.update(SCHOLAR_SIGNED_INPUT=str(path), PSMODULEPATH=str(shell.parent/'Modules'))
    command = ("Import-Module Microsoft.PowerShell.Security -ErrorAction Stop;"
               "$s=Get-AuthenticodeSignature -LiteralPath $env:SCHOLAR_SIGNED_INPUT;"
               "if($s.Status -ne 'Valid' -or $s.SignerCertificate.Subject -notmatch 'O=Microsoft Corporation'){exit 1}")
    subprocess.run([str(shell), '-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', command], env=env, check=True)


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')


def build(args):
    if os.name!='nt' or platform.machine().lower() not in ('amd64', 'x86_64'):
        raise ValueError('Build this edition on Windows x64.')
    plan = json.loads((ROOT/'scripts/install/windows-x64.json').read_text(encoding='utf-8'))
    tools = json.loads((ROOT/'scripts/standalone/tools.json').read_text(encoding='utf-8'))
    version = json.loads((ROOT/'package.json').read_text(encoding='utf-8'))['version']
    output = ROOT/'dist/standalone'
    output.mkdir(parents=True, exist_ok=True)
    webview = args.webview_installer.absolute()
    if sha(webview)!=tools['webview2']['sha256']:
        raise ValueError('WebView2 checksum differs from scripts/standalone/tools.json; explicitly refresh the lock after verifying the official download.')
    verify_microsoft_signature(webview)
    if not args.iscc.is_file():
        raise ValueError('Install Inno Setup 7, then pass --iscc.')
    crt = args.vc_crt.absolute()
    if crt.name!='Microsoft.VC143.CRT' or crt.parent.name!='x64':
        raise ValueError('--vc-crt must name the VS2022 Redist/MSVC/<version>/x64/Microsoft.VC143.CRT folder.')
    dlls = sorted(crt.glob('*.dll'))
    if not {'msvcp140.dll', 'vcruntime140.dll', 'vcruntime140_1.dll'} <= {p.name for p in dlls}:
        raise ValueError('Incomplete x64 CRT redistributable folder.')
    for dll in dlls:
        verify_microsoft_signature(dll)
    original = json.loads((ROOT/'source-manifest.json').read_text(encoding='utf-8'))
    validate(ROOT, original)
    if original['platform']!='windows-x64' or original['version']!=version:
        raise ValueError('Build the matching Windows source-release app first.')
    app_zip = ROOT/f'dist/release/ScholarNoteLM-{version}-windows-x64.zip'
    with zipfile.ZipFile(app_zip) as archive:
        if archive.read('ScholarNoteLM.exe')!=(ROOT/'ScholarNoteLM.exe').read_bytes() or json.loads(archive.read('source-manifest.json'))!=original:
            raise ValueError('App, source manifest and existing release ZIP must match.')
    assets = asset_manifest(ROOT)
    for item in assets:
        if not matches(safe_path(ROOT,item['path']),item):
            raise ValueError('Missing or changed offline model/font: '+item['path'])
    public = source_files()
    cuda = cuda_payload(ROOT) if args.include_cuda else None
    print(f'Preflight passed: {len(public)} source files, {len(assets)} verified model/font files.', flush=True)
    # Each build starts in a new directory; no recursive deletion of existing files.
    stage = output/f'stage-{version}-{uuid.uuid4().hex[:8]}'
    stage.mkdir()
    app = stage/'app'
    for name in public:
        copy_file(ROOT/name, app/name)
    for name in ('ScholarNoteLM.exe', 'source-manifest.json'):
        copy_file(ROOT/name, app/name)
    with zipfile.ZipFile(app_zip) as archive:
        for name in archive.namelist():
            if name.startswith('third-party/') and not name.endswith('/'):
                target = safe_path(app,name)
                target.parent.mkdir(parents=True,exist_ok=True)
                target.write_bytes(archive.read(name))
    print('Copying managed runtimes and models (no developer toolchain or user data)...', flush=True)
    for component in RUNTIME_NAMES:
        for file in runtime_files(ROOT,component):
            copy_file(file, app/file.relative_to(ROOT))
    if cuda:
        for file in runtime_files(ROOT,cuda['directory']):
            copy_file(file, app/file.relative_to(ROOT))
        write_json(app/'runtimes/cuda-state.json',
                   {key:cuda[key] for key in ('schemaVersion','ready','directory','profile','fingerprint')})
    node_modules = ROOT/'services/downloader/node_modules'
    for directory, folders, files in os.walk(node_modules, followlinks=False):
        folders[:] = [n for n in folders if n not in ('.bin', '.cache')]
        for name in files:
            file = Path(directory)/name
            copy_file(file, app/file.relative_to(ROOT))
    for item in assets:
        copy_file(ROOT/item['path'],app/item['path'])
    # App-local CRT deployment: no system redist install or admin elevation needed.
    destinations = [app, app/'runtimes/python'/plan['python'],
                    app/'runtimes/marker/Lib/site-packages/torch/lib']
    destinations += [app/'runtimes'/kind/'Scripts' for kind in ('downloader','marker','retrieval')]
    if cuda:
        destinations += [app/'runtimes'/cuda['directory']/'Scripts',
                         app/'runtimes'/cuda['directory']/'Lib/site-packages/torch/lib']
    for destination in destinations:
        for dll in dlls:
            copy_file(dll,destination/dll.name)
    compiler = Path(os.environ['WINDIR'])/'Microsoft.NET/Framework64/v4.0.30319/csc.exe'
    subprocess.run([str(compiler),'/nologo','/target:winexe','/platform:x64','/utf8output',
                    '/reference:System.Windows.Forms.dll','/win32icon:'+str(ROOT/'apps/desktop/src-tauri/icons/icon.ico'),
                    '/out:'+str(stage/'ScholarNoteLM-Standalone.exe'),str(ROOT/'scripts/standalone/launcher.cs')],check=True)
    readme = '''ScholarNoteLM Windows x64 offline edition

This installer includes the application, matching source, Python dependencies,
CPU models, Node, Chromium, fonts, app-local Microsoft VC runtime, and the
official offline WebView2 installer. No Git, Python, Rust or CUDA setup is needed.

Install into a writable folder for this user. Start ScholarNoteLM Standalone
from the desktop/start menu. First use asks for a research folder and your model
service settings. PubMed and remote model APIs still need a network connection.

Do not copy personal config, data or research files into a distribution package.
The original source-install edition is separate and is not overwritten.
Uninstall removes packaged files; generated settings and research data remain.
Moving the entire installed folder is supported: use the standalone launcher
to repair Python paths automatically. Do not move only the executable.

To verify: ScholarNoteLM-Standalone.exe --check
Result log: app\\tmp\\standalone-check.log

This first build targets Windows 10/11 x64 (Intel/AMD), not ARM64. Clean-machine
and Windows 10 validation must be recorded separately; a developer-machine
smoke test does not establish that coverage. Executables are currently unsigned.

Source/license notices are under app, including app/scripts/install/ASSET_NOTICES.md.
Bundling models does not change their licenses. The source revision and hashes
of every packaged resource are recorded in standalone-manifest.json.
Microsoft CRT redist: https://learn.microsoft.com/cpp/windows/redistributing-visual-cpp-files
WebView2 distribution: https://learn.microsoft.com/microsoft-edge/webview2/concepts/distribution
'''
    if cuda:
        readme += ('\nDistribution: extract the entire ZIP into one folder. Keep the setup EXE\n'
                   'and every accompanying .bin file together, then run the setup EXE.\n'
                   'All installation data is offline; the data files are not downloads.\n'
                   '\nBundled NVIDIA acceleration: PyTorch '+cuda['torch']+'.\n'
                   'A compatible NVIDIA GPU and installed NVIDIA driver are required;\n'
                   'the NVIDIA display driver is not bundled. This profile uses driver '+
                   cuda['minimumWindowsDriver']+' or newer as its supported baseline.\n'
                   'The app probes actual GPU operation and falls back to the separate CPU runtime.\n'
                   'No system CUDA Toolkit or network download is needed. This package contains\n'
                   'one CUDA profile; GPUs unsupported by that profile use CPU.\n')
    (stage/'INSTALL-README.txt').write_text(readme,encoding='utf-8')
    records = {}
    for file in sorted(stage.rglob('*')):
        if file.is_file():
            records[file.relative_to(stage).as_posix()]={'bytes':file.stat().st_size,'sha256':sha(file)}
    metadata = {'schemaVersion':1,'platform':'windows-x64','version':version,
                'cuda':cuda,
                'python':plan['python'],'sourceCommit':git('rev-parse','HEAD').decode().strip(),
                'sourceTreeDirty':bool(git('status','--porcelain').strip()),
                'sourceFiles':{name:sha(ROOT/name) for name in public},
                'webview2':tools['webview2'],
                'vcRuntime':{'version':crt.parent.parent.name,'files':{p.name:sha(p) for p in dlls}},
                'files':records}
    write_json(stage/'standalone-manifest.json',metadata)
    # An explicit installer file list prevents smoke-test output or private files
    # ever being picked up by a recursive wildcard on a reused staging folder.
    files_list = stage/'installer-files.iss'
    lines = []
    for name in [*records,'standalone-manifest.json']:
        path = Path(name)
        source = str(stage/path).replace('"','""')
        dest = ('{app}\\'+str(path.parent)) if path.parent!=Path('.') else '{app}'
        lines.append(f'Source: "{source}"; DestDir: "{dest}"; Flags: ignoreversion')
    files_list.write_text('\n'.join(lines)+'\n',encoding='utf-8-sig')
    write_json(stage/'build-info.json',{'stage':str(stage),'filesList':str(files_list),
               'payloadBytes':sum(v['bytes'] for v in records.values()),'fileCount':len(records)})
    print(f'Staged {len(records)} files, {sum(v["bytes"] for v in records.values())/1024**3:.2f} GiB: {stage}',flush=True)
    if args.stage_only:
        return
    compile_installer(stage,files_list,args,version,cuda)
    if not args.keep_build:
        cleanup_stage(stage,output)


def cleanup_stage(stage,output):
    """Delete only this successful build's owned intermediate directory."""
    reject_links(stage)
    stage=stage.resolve();output=output.resolve()
    if stage.parent!=output or not re.fullmatch(r'stage-[0-9]+\.[0-9]+\.[0-9]+-[0-9a-f]{8}',stage.name):
        raise ValueError('Refusing to clean a path outside an owned staging directory.')
    if not (stage/'build-info.json').is_file():
        raise ValueError('Refusing to clean staging without build ownership metadata.')
    for directory,folders,files in os.walk(stage,followlinks=False):
        for name in folders+files:
            reject_links(Path(directory)/name)
    shutil.rmtree(stage)


def publish_distribution(stage,output,installer,payloads,cuda):
    """Validate a complete private build before replacing public artifacts."""
    checksums=installer.with_suffix('.exe.sha256')
    checksums.write_text(''.join(sha(path)+'  '+path.name+'\n' for path in payloads),encoding='utf-8')
    artifact=installer
    if cuda:
        artifact=installer.parent/(installer.name.removesuffix('-setup.exe')+'-cuda.zip')
        with zipfile.ZipFile(artifact,'w',compression=zipfile.ZIP_STORED,allowZip64=True) as archive:
            for path in [*payloads,checksums,stage/'INSTALL-README.txt']:
                archive.write(path,path.name)
        with zipfile.ZipFile(artifact) as archive:
            damaged=archive.testzip()
        if damaged:
            raise ValueError('Distribution ZIP integrity check failed: '+damaged)
        checksums=artifact.with_suffix('.zip.sha256')
        checksums.write_text(sha(artifact)+'  '+artifact.name+'\n',encoding='utf-8')
    # Build outputs remain private until compilation and archive validation pass.
    # Each file replacement is atomic on this filesystem; verify the sidecar when downloading.
    final=output/artifact.name
    os.replace(artifact,final)
    os.replace(checksums,output/checksums.name)
    print('Complete offline distribution:',final,flush=True)
    return final


def compile_installer(stage,files_list,args,version,cuda):
    output = stage/'installer-output'
    output.mkdir()
    webview = args.webview_installer.absolute()
    log = stage/'installer-build.log'
    command = [str(args.iscc), '/Qp', '/DAppVersion='+version, '/DOutputDir='+str(output),
               '/DPayloadDir='+str(stage), '/DFilesList='+str(files_list),
               '/DIconFile='+str(ROOT/'apps/desktop/src-tauri/icons/icon.ico'),
               '/DWebViewInstaller='+str(webview), str(ROOT/'scripts/standalone/installer.iss')]
    if cuda:
        command.insert(1,'/DBundleCuda=1')
    print('Compiling the full offline installer; progress is recorded in '+str(log),flush=True)
    with log.open('w',encoding='utf-8') as stream:
        result = subprocess.run(command,stdout=stream,stderr=subprocess.STDOUT)
    if result.returncode:
        print(log.read_text(encoding='utf-8',errors='replace')[-6000:])
        raise ValueError('Installer compiler failed; staging is retained for diagnosis.')
    installer = output/f'ScholarNoteLM-{version}-windows-x64-standalone-setup.exe'
    payloads = [installer]
    if cuda:
        payloads += sorted(output.glob(installer.stem+'-*.bin'))
        if len(payloads)<2:
            raise ValueError('CUDA installer is missing its offline data file.')
    print(json.dumps({'installer':str(installer),'payloadBytes':sum(p.stat().st_size for p in payloads),
                      'files':[p.name for p in payloads]},indent=2),flush=True)
    publish_distribution(stage,stage.parent,installer,payloads,cuda)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iscc',type=Path,default=ROOT/'cache/standalone-tools/inno/ISCC.exe')
    parser.add_argument('--webview-installer',type=Path,default=ROOT/'cache/standalone-tools/MicrosoftEdgeWebView2RuntimeInstallerX64.exe')
    parser.add_argument('--vc-crt',type=Path,required=True)
    parser.add_argument('--stage-only',action='store_true')
    parser.add_argument('--keep-build',action='store_true',help='Retain this build staging directory and compiler log after success')
    parser.add_argument('--include-cuda',action='store_true',help='Bundle the installed managed CUDA overlay alongside the CPU fallback')
    build(parser.parse_args())


if __name__=='__main__':
    main()
